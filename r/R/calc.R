#' Double a numeric value
#'
#' Starter function. Each R-stack ticket adds a sibling function here.
#'
#' @param n numeric scalar
#' @return n * 2
#' @export
double_value <- function(n) {
  n * 2
}

#' Triple a numeric value
#'
#' @param n numeric scalar
#' @return n * 3
#' @export
triple_value <- function(n) {
  n * 3
}
